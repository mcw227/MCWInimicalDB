CREATE VIEW dinner_menu_view AS
SELECT * FROM items
JOIN menu_items ON items.id = menu_items.item_id AND menu_items.menu_id = 2;

CREATE VIEW lunch_menu_view AS
SELECT * FROM items
JOIN menu_items ON items.id = menu_items.item_id AND menu_items.menu_id = 1;

CREATE VIEW dessert_menu_view AS
SELECT * FROM items
JOIN menu_items ON items.id = menu_items.item_id AND menu_items.menu_id = 3;

CREATE VIEW signature_item_view AS
SELECT items.id, items.name, items.price FROM items
JOIN signature_items ON items.id = signature_items.id;

CREATE VIEW customer_creations_view AS
SELECT i.id, i.name, i.price, c.creator
FROM items i
JOIN customer_creations c ON i.id = c.id;

CREATE VIEW ingredients AS
SELECT * FROM items
WHERE NOT EXISTS (
    SELECT sig.id FROM signature_items sig WHERE sig.id = items.id
);

-- This trigger allows us to update the cost of signature items when ingredients are added or removed from them
-- Please note that for this specific query, AI sources were consulted in order to understand how to obtain the values of the 
create or replace TRIGGER upd_item_price
AFTER INSERT OR DELETE ON recipes
FOR EACH ROW
DECLARE 
    ingredient_price NUMBER;
    added_cost NUMBER;
BEGIN

    IF INSERTING THEN
        SELECT price INTO ingredient_price
        FROM ingredients
        WHERE id = :NEW.ingredient_id;

        added_cost := ingredient_price * :NEW.quantity;

    ELSIF DELETING THEN
        SELECT price INTO ingredient_price
        FROM ingredients
        WHERE id = :OLD.ingredient_id;

        added_cost := ingredient_price * :OLD.quantity * -1;

    END IF;

    UPDATE items
    SET price = nvl(price, 0) + added_cost
    WHERE items.id = nvl(:NEW.recipe_id, :OLD.recipe_id);

EXCEPTION
    WHEN NO_DATA_FOUND THEN
    NULL;

END;
