CREATE TABLE locations (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    address varchar(50) NOT NULL,
    phone char(20) NOT NULL,     -- format "+1 888 888 8888"
    sales_tax NUMBER(4,2) NOT NULL
);

CREATE TABLE customers (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    name varchar(30) NOT NULL,
    email varchar(40) NOT NULL,
    membership number(1) NOT NULL,
    points number(7) DEFAULT 0,
    active number(1) DEFAULT 1,
    CONSTRAINT customer_membership_chk
        CHECK (membership BETWEEN 0 AND 1),
    CONSTRAINT customer_active_chk
        CHECK (active BETWEEN 0 AND 1)
);

CREATE TABLE phone_numbers (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    phone char(20), --- format "+1888-888-8888"
    customer_id NUMBER,
    CONSTRAINT cust_phone
        FOREIGN KEY (customer_id)
        REFERENCES customers(id) ON DELETE CASCADE
);

CREATE TABLE cards (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    customer_id NUMBER,
    brand varchar(40) NOT NULL,
    name varchar(30) NOT NULL,
    card_number char(20),
    expr_date char(7) NOT NULL, -- format 2024-08
    cvv char(3) NOT NULL,
    active number(1) DEFAULT 1,
    CONSTRAINT fk_cards
        FOREIGN KEY (customer_id)
        REFERENCES customers(id) ON DELETE CASCADE,
    CONSTRAINT card_active_chk
        CHECK (active BETWEEN 0 AND 1)
);

CREATE TABLE items (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    name varchar(50),
    price NUMBER(5,2)
);

CREATE TABLE customer_creations (
    id NUMBER PRIMARY KEY,
    creator varchar(30),
    CONSTRAINT cc_fk
        FOREIGN KEY (id)
        REFERENCES items(id) ON DELETE CASCADE
);

CREATE TABLE signature_items (
    id NUMBER PRIMARY KEY,
    CONSTRAINT sig_fk
        FOREIGN KEY (id)
        REFERENCES items(id) ON DELETE CASCADE
);

CREATE TABLE recipes (
    recipe_id NUMBER,
    ingredient_id NUMBER,
    quantity NUMBER(2),
    CONSTRAINT recipe_target_fk
        FOREIGN KEY (recipe_id)
        REFERENCES customer_creations(id) ON DELETE CASCADE,
    CONSTRAINT recipe_ingredient_fk
        FOREIGN KEY (ingredient_id)
        REFERENCES items(id) ON DELETE CASCADE,
    CONSTRAINT recipe_pk
        PRIMARY KEY (recipe_id, ingredient_id),
    CONSTRAINT recipe_quantity_chk
        CHECK (quantity > 0)
);

CREATE TABLE menus (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    name varchar(20)
);

CREATE TABLE menu_items (
    menu_id NUMBER,
    item_id NUMBER,
    CONSTRAINT menu_id_fk
        FOREIGN KEY (menu_id)
        REFERENCES menus(id) ON DELETE CASCADE,
    CONSTRAINT item_id_fk
        FOREIGN KEY (item_id)
        REFERENCES items(id) ON DELETE CASCADE,
    CONSTRAINT menu_item_pk
        PRIMARY KEY (menu_id, item_id)
);

CREATE TABLE orders (
    id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    location_id NUMBER NOT NULL,
    customer_id NUMBER NOT NULL,
    payment_id NUMBER,
    status NUMBER,
    total NUMBER(6,2),
    CONSTRAINT loc_fk
        FOREIGN KEY (location_id)
        REFERENCES locations(id) ON DELETE CASCADE,
    CONSTRAINT customer_fk
        FOREIGN KEY (customer_id)
        REFERENCES customers(id) ON DELETE CASCADE,
    CONSTRAINT pay_fk
        FOREIGN KEY (payment_id)
        REFERENCES cards(id) ON DELETE CASCADE,
    CONSTRAINT status_chk
        CHECK (status BETWEEN 0 AND 4) -- CANCELLED, RECIEVED, IN-PROGRESS, WAITING-FOR PICKUP, COMPLETED
);

CREATE TABLE order_items (
    order_id NUMBER,
    item_id NUMBER,
    quantity NUMBER NOT NULL,
    price NUMBER(5,2) NOT NULL, --individual item cost. This needs to be set like this to account for price adjustments based on location
    CONSTRAINT order_id_fk
        FOREIGN KEY (order_id)
        REFERENCES orders(id) ON DELETE CASCADE,
    CONSTRAINT order_item_fk
        FOREIGN KEY (item_id)
        REFERENCES items(id) ON DELETE CASCADE,
    CONSTRAINT order_items_pk
        PRIMARY KEY (order_id, item_id),
    CONSTRAINT order_quantity_chk
        CHECK (quantity > 0)
);

CREATE TABLE price_change (
    item_id number,
    location_id number,
    price number(5,2),
    CONSTRAINT pc_item_fk
